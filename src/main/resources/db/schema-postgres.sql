-- * prod(ddl-auto=validate)와 B02 적재는 이 스크립트로 만든 테이블을 전제로 한다.
-- * 엔티티(com.jigeumgayong.backend.facility/analysis .domain)의 컬럼명·타입·길이와 맞춰져 있다.
--   엔티티를 바꾸면 이 파일도 같이 바꿀 것.
-- * classpath 루트가 아니라 db/ 아래라서 Spring Boot가 자동 실행하지 않는다. 수동 실행용.
--   예: psql -d <db> -f src/main/resources/db/schema-postgres.sql
-- * local(H2)은 Hibernate가 테이블을 만들며 CHECK·복합 FK는 만들지 않는다.

-- ---------------------------------------------------------------
-- 2. facility_type (시설 유형)
-- ---------------------------------------------------------------
CREATE TABLE facility_type (
    type_id       SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(30)  NOT NULL UNIQUE,
    chip_group    VARCHAR(20)  NOT NULL,
    default_image VARCHAR(255),
    CONSTRAINT ck_facility_type_chip_group
        CHECK (chip_group IN ('도서관', '체육시설', '문화공간', '복지시설'))
);

-- ---------------------------------------------------------------
-- 3. facility (공공시설)
-- ---------------------------------------------------------------
CREATE TABLE facility (
    facility_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_id           SMALLINT      NOT NULL REFERENCES facility_type (type_id),
    source_type       VARCHAR(30)   NOT NULL,
    source_key        VARCHAR(100)  NOT NULL,
    district          VARCHAR(10)   NOT NULL,
    access_type       VARCHAR(20)   NOT NULL DEFAULT 'OPEN_HOURS',
    name              VARCHAR(100)  NOT NULL,
    address           VARCHAR(255)  NOT NULL,
    latitude          NUMERIC(9, 6) NOT NULL,
    longitude         NUMERIC(9, 6) NOT NULL,
    phone             VARCHAR(20),
    closed_day_note   VARCHAR(255),
    bus_stop_count    INTEGER,
    bus_counted_at    DATE,
    source_updated_at DATE,
    loaded_at         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_facility_source UNIQUE (source_type, source_key),
    CONSTRAINT ck_facility_source_type
        CHECK (source_type IN ('LIB_STD', 'LIB_SMALL', 'PUBLIC_OPEN', 'ADMIN_CENTER', 'MANUAL')),
    CONSTRAINT ck_facility_district
        CHECK (district IN ('수지구', '기흥구', '처인구')),
    CONSTRAINT ck_facility_access_type
        CHECK (access_type IN ('OPEN_HOURS', 'RESERVATION', 'ALWAYS_OPEN')),
    -- (0,0) 같은 가짜 좌표 차단 (R16)
    CONSTRAINT ck_facility_latitude  CHECK (latitude  BETWEEN 37.0 AND 37.5),
    CONSTRAINT ck_facility_longitude CHECK (longitude BETWEEN 126.9 AND 127.5),
    -- NULL=미확인, 0=확인 결과 0곳 (R14)
    CONSTRAINT ck_facility_bus_stop_count CHECK (bus_stop_count IS NULL OR bus_stop_count >= 0)
);

CREATE INDEX idx_facility_district_type ON facility (district, type_id);

-- ---------------------------------------------------------------
-- 4. facility_amenity (편의시설 태그)
-- ---------------------------------------------------------------
CREATE TABLE facility_amenity (
    facility_id  BIGINT      NOT NULL REFERENCES facility (facility_id) ON DELETE CASCADE,
    amenity_code VARCHAR(20) NOT NULL,
    detail       VARCHAR(100),
    PRIMARY KEY (facility_id, amenity_code),
    CONSTRAINT ck_facility_amenity_code CHECK (amenity_code IN ('PARKING', 'RENTAL_ROOM'))
);

-- ---------------------------------------------------------------
-- 5. facility_space (시설 공간)
-- ---------------------------------------------------------------
CREATE TABLE facility_space (
    facility_id BIGINT      NOT NULL REFERENCES facility (facility_id) ON DELETE CASCADE,
    space_type  VARCHAR(20) NOT NULL DEFAULT 'DEFAULT',
    space_name  VARCHAR(30) NOT NULL,
    PRIMARY KEY (facility_id, space_type),
    CONSTRAINT ck_facility_space_type CHECK (space_type IN ('GENERAL', 'READING', 'DEFAULT'))
);

-- ---------------------------------------------------------------
-- 6. operating_hour (공간·요일·구간별 운영시간)
--    시각은 자정부터의 분. 24:00 = 1440
-- ---------------------------------------------------------------
CREATE TABLE operating_hour (
    facility_id  BIGINT      NOT NULL,
    space_type   VARCHAR(20) NOT NULL,
    day_of_week  SMALLINT    NOT NULL,
    interval_seq SMALLINT    NOT NULL DEFAULT 1,
    day_state    VARCHAR(10) NOT NULL,
    open_min     SMALLINT,
    close_min    SMALLINT,
    PRIMARY KEY (facility_id, space_type, day_of_week, interval_seq),
    -- 존재하지 않는 공간의 운영시간은 들어갈 수 없다
    CONSTRAINT fk_operating_hour_space FOREIGN KEY (facility_id, space_type)
        REFERENCES facility_space (facility_id, space_type) ON DELETE CASCADE,
    CONSTRAINT ck_operating_hour_day     CHECK (day_of_week BETWEEN 0 AND 6),
    CONSTRAINT ck_operating_hour_seq     CHECK (interval_seq >= 1),
    CONSTRAINT ck_operating_hour_state   CHECK (day_state IN ('OPEN', 'CLOSED', 'UNKNOWN')),
    CONSTRAINT ck_operating_hour_open    CHECK (open_min  BETWEEN 0 AND 1439),
    CONSTRAINT ck_operating_hour_close   CHECK (close_min BETWEEN 1 AND 1440),
    -- OPEN: 시간 필수, open_min < close_min
    -- CLOSED / UNKNOWN: 시간 NULL, interval_seq = 1
    CONSTRAINT ck_operating_hour_rule CHECK (
        (day_state = 'OPEN'
            AND open_min IS NOT NULL AND close_min IS NOT NULL AND open_min < close_min)
        OR
        (day_state IN ('CLOSED', 'UNKNOWN')
            AND open_min IS NULL AND close_min IS NULL AND interval_seq = 1)
    )
);

CREATE INDEX idx_operating_hour_search
    ON operating_hour (day_of_week, day_state, open_min, close_min);

-- ---------------------------------------------------------------
-- 7. ai_analysis (AI 분석 캐시, 범용)
-- ---------------------------------------------------------------
CREATE TABLE ai_analysis (
    analysis_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_key      VARCHAR(40) NOT NULL,
    analysis_type  VARCHAR(30) NOT NULL,
    params_key     VARCHAR(40) NOT NULL DEFAULT '',
    facility_id    BIGINT REFERENCES facility (facility_id) ON DELETE CASCADE,
    space_type     VARCHAR(20),
    payload        JSONB       NOT NULL,
    source_hash    CHAR(64)    NOT NULL,
    prompt_version VARCHAR(20) NOT NULL,
    model_name     VARCHAR(50),
    created_at     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- PostgreSQL에는 ON UPDATE가 없다. 갱신은 JPA @UpdateTimestamp가 담당
    updated_at     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ai_analysis_scope_type_params UNIQUE (scope_key, analysis_type, params_key),
    -- 공간 단위 행: 존재하지 않는 시설·공간의 결과는 들어갈 수 없다
    -- (facility_id 또는 space_type이 NULL이면 이 FK는 검사하지 않는다: MATCH SIMPLE)
    CONSTRAINT fk_ai_analysis_space FOREIGN KEY (facility_id, space_type)
        REFERENCES facility_space (facility_id, space_type) ON DELETE CASCADE,
    CONSTRAINT ck_ai_analysis_type
        CHECK (analysis_type IN ('ACCESSIBILITY', 'VULNERABLE_AREA', 'IMPROVEMENT', 'REGION_INSIGHT')),
    CONSTRAINT ck_ai_analysis_space_type
        CHECK (space_type IS NULL OR space_type IN ('GENERAL', 'READING', 'DEFAULT')),
    CONSTRAINT ck_ai_analysis_payload CHECK (jsonb_typeof(payload) = 'object')
);
